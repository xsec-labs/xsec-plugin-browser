import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const json = async path => JSON.parse(await readFile(join(root, path), 'utf8'));
const manifest = await json('plugin.json'), catalog = await json('.codex-plugin/plugin.json');
const extension = manifest.extensions['com.xsec.desktop'];
assert.equal(manifest.name, 'com.xsec.workspace.browser');
assert.equal(catalog.name, manifest.name); assert.equal(catalog.version, manifest.version);
assert.equal(extension.schemaVersion, 2);
assert.equal(extension.entrypoints.frontend, './com.xsec.desktop/frontend/index.js');
assert.equal(extension.frontendApi.version, 2); assert.equal(extension.frontendApi.module, 'single-esm');
assert.deepEqual(Object.keys(extension.permissions).sort(), ['workspace.project.read', 'workspace.session.read', 'browser.control', 'pluginData.read', 'pluginData.write', 'mcp.servers.register', 'native.execute'].sort());
assert.deepEqual(await json('mcp.json'), { mcpServers: { browser: { type: 'stdio', command: './bin/browser-mcp', cwd: '${PLUGIN_ROOT}' } } });
const contractBytes = await readFile(join(root, 'contracts/browser-contract-v3.json'));
assert.equal(createHash('sha256').update(contractBytes).digest('hex'), extension.browserContract.sha256);
const contract = JSON.parse(contractBytes), tools = Object.keys(contract.tools).sort();
assert.equal(tools.length, 53); assert.ok(tools.every(tool => tool.startsWith('browser_')));
assert.deepEqual(Object.values(extension.contributes.agentTools).map(binding => binding.mcpTool).sort(), tools);
const skills = (await readdir(join(root, 'skills'), { withFileTypes: true })).filter(entry => entry.isDirectory()).map(entry => entry.name).sort();
assert.deepEqual(skills, ['browser-evidence-replay', 'browser-forms-dialogs', 'browser-locator-interaction', 'browser-navigation-tabs', 'browser-network-console', 'browser-page-evaluate', 'browser-session-lifecycle', 'browser-state-storage']);
for (const skill of skills) assert.ok((await readFile(join(root, 'skills', skill, 'SKILL.md'))).length > 0);
const controller = await readFile(join(root, 'frontend-src/controller.js'), 'utf8');
const methods = [...new Set([...controller.matchAll(/host\.request\("([^\"]+)"/g)].map(match => match[1]))].sort();
assert.deepEqual(methods, Object.keys(extension.frontendApi.methods).sort());
console.log('PASS: dual manifests, capabilities, 20 frontend methods, 53 MCP tools, 8 skills and v3 digest');
